import { writeFile } from "node:fs/promises";
import { relative } from "node:path";

const outputPath = "BEHAVIOR_INDEX_FOR_HUMANS.md";
const flatOutputPath = "BEHAVIOR_INDEX.md";

export default class AppBehaviorReporter {
  async onTestRunEnd(testModules) {
    // The doc is committed from local runs, so there's no reason for a build server to regenerate it.
    if (process.env.CI) return;

    const rootGroup = { children: new Map(), tests: [] };
    const flatNames = [];

    for (const testModule of testModules) {
      for (const testCase of testModule.children.allTests()) {
        flatNames.push(testCase.fullName);
        const parts = testCase.fullName.split(" > ");
        // Forward-slash path so the link opens the file in PyCharm and on GitHub.
        // No line number: GitHub needs `#L`, PyCharm wants `:`, and neither honors the
        // other, so a plain path is the only form that opens the file in both.
        const relativePath = relative(process.cwd(), testModule.moduleId).replaceAll("\\", "/");
        addTest(rootGroup, parts, relativePath);
      }
    }

    const lines = ["<!-- Autogenerated by appBehaviorReporter.js -->", "# Behavior Index", ""];
    appendGroupLines(lines, rootGroup, 0);
    await writeFile(outputPath, `${lines.join("\n").trimEnd()}\n`);

    // Flat format: one line per test so that an agent grepping this file gets back
    // a complete, self-contained match rather than a leaf detached from its describe context.
    const flatLines = [
      "<!-- Autogenerated by appBehaviorReporter.js -->",
      "# Behavior Index",
      "",
      ...flatNames,
    ];
    await writeFile(flatOutputPath, `${flatLines.join("\n").trimEnd()}\n`);
  }
}

function addTest(group, parts, link) {
  if (parts.length === 1) {
    group.tests.push({ name: parts[0], link });
    return;
  }

  const [describeName, ...remainingParts] = parts;
  const childGroup = group.children.get(describeName) ?? { children: new Map(), tests: [] };
  group.children.set(describeName, childGroup);
  addTest(childGroup, remainingParts, link);
}

function appendGroupLines(lines, group, depth) {
  const indent = "  ".repeat(depth);
  for (const test of group.tests) {
    lines.push(`${indent}- [${test.name}](${test.link})`);
  }
  for (const [name, childGroup] of group.children) {
    lines.push(`${indent}- ${name}`);
    appendGroupLines(lines, childGroup, depth + 1);
  }
}
